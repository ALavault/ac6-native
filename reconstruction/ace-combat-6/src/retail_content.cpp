std::uint32_t read_be32(const std::uint8_t* bytes) noexcept {
  return (static_cast<std::uint32_t>(bytes[0]) << 24u) |
         (static_cast<std::uint32_t>(bytes[1]) << 16u) |
         (static_cast<std::uint32_t>(bytes[2]) << 8u) |
         static_cast<std::uint32_t>(bytes[3]);
}

void append_u32(std::vector<std::uint8_t>& output, std::uint32_t value) {
  output.push_back(static_cast<std::uint8_t>(value >> 24u));
  output.push_back(static_cast<std::uint8_t>(value >> 16u));
  output.push_back(static_cast<std::uint8_t>(value >> 8u));
  output.push_back(static_cast<std::uint8_t>(value));
}

void append_u64(std::vector<std::uint8_t>& output, std::uint64_t value) {
  append_u32(output, static_cast<std::uint32_t>(value >> 32u));
  append_u32(output, static_cast<std::uint32_t>(value));
}

void append_digest(std::vector<std::uint8_t>& output, const Sha256Digest& digest) {
  output.insert(output.end(), digest.begin(), digest.end());
}

bool add_within(std::uint64_t left, std::uint64_t right,
                std::uint64_t limit) noexcept {
  return left <= limit && right <= limit - left;
}

bool read_file(const std::filesystem::path& path, std::uint64_t maximum_size,
               std::vector<std::uint8_t>& bytes) {
  std::error_code error;
  const std::uintmax_t size = std::filesystem::file_size(path, error);
  if (error || size > maximum_size || size > std::numeric_limits<std::size_t>::max()) {
    return false;
  }
  std::ifstream input(path, std::ios::binary);
  if (!input) return false;
  bytes.resize(static_cast<std::size_t>(size));
  if (!bytes.empty()) {
    input.read(reinterpret_cast<char*>(bytes.data()),
               static_cast<std::streamsize>(bytes.size()));
  }
  return input && input.peek() == std::ifstream::traits_type::eof();
}

bool read_range(const std::filesystem::path& path, std::uint64_t offset,
                std::uint64_t size, std::vector<std::uint8_t>& bytes) {
  if (size > std::numeric_limits<std::size_t>::max() ||
      offset > static_cast<std::uint64_t>(std::numeric_limits<std::streamoff>::max())) {
    return false;
  }
  std::ifstream input(path, std::ios::binary);
  if (!input) return false;
  input.seekg(static_cast<std::streamoff>(offset));
  if (!input) return false;
  bytes.resize(static_cast<std::size_t>(size));
  if (!bytes.empty()) {
    input.read(reinterpret_cast<char*>(bytes.data()),
               static_cast<std::streamsize>(bytes.size()));
  }
  return input && static_cast<std::size_t>(input.gcount()) == bytes.size();
}

bool qualify_file(const std::filesystem::path& path, std::uint64_t expected_size,
                  const Sha256Digest& expected_digest, Sha256Digest& actual) {
  std::error_code error;
  if (!std::filesystem::is_regular_file(path, error) || error ||
      std::filesystem::file_size(path, error) != expected_size || error) {
    return false;
  }
  return sha256_file(path, actual, expected_size) && actual == expected_digest;
}

RetailContentError qualify_source_files(const std::filesystem::path& source,
                                        const RetailIdentityPolicy& policy,
                                        std::string& detail) {
  Sha256Digest actual{};
  const auto files = std::array{
      std::pair{source / "default.xex",
                std::pair{policy.identity.xex_size, policy.identity.xex_sha256}},
      std::pair{source / "DATA.TBL",
                std::pair{policy.identity.data_table_size,
                          policy.identity.data_table_sha256}},
      std::pair{source / "DATA00.PAC",
                std::pair{policy.identity.data00_size, policy.identity.data00_sha256}},
      std::pair{source / "DATA01.PAC",
                std::pair{policy.identity.data01_size, policy.identity.data01_sha256}},
  };
  for (const auto& qualified : files) {
    std::error_code error;
    if (!std::filesystem::is_regular_file(qualified.first, error) || error) {
      detail = "missing retail source file: " + qualified.first.filename().string();
      return RetailContentError::SourceMissing;
    }
    if (!qualify_file(qualified.first, qualified.second.first,
                      qualified.second.second, actual)) {
      detail = "retail identity mismatch: " + qualified.first.filename().string();
      return RetailContentError::SourceIdentityMismatch;
    }
  }
  if (policy.media.required) {
    for (const auto& asset : policy.media.assets) {
      if (asset.filename == nullptr || asset.size == 0 || asset.sha256 == Sha256Digest{}) {
        detail = "media policy contains an unresolved identity";
        return RetailContentError::SourceIdentityMismatch;
      }
      const auto path = source / asset.filename;
      if (!qualify_file(path, asset.size, asset.sha256, actual)) {
        detail = "retail media identity mismatch: " + path.filename().string();
        return RetailContentError::SourceIdentityMismatch;
      }
    }
  }
  return RetailContentError::None;
}

std::filesystem::path archive_path(const std::filesystem::path& source,
                                   RetailArchive archive) {
  return source / (archive == RetailArchive::Data00 ? "DATA00.PAC" : "DATA01.PAC");
}

std::filesystem::path blob_path(const std::filesystem::path& cache,
                                const Sha256Digest& digest) {
  const std::string hex = sha256_hex(digest);
  return cache / "blobs" / "sha256" / hex.substr(0, 2) / hex;
}

bool parse_table(std::span<const std::uint8_t> bytes,
                 const RetailIdentityPolicy& policy,
                 const RetailImportLimits& limits,
                 std::vector<TableEntry>& entries,
                 std::string& detail) {
  if (bytes.size() < 8) {
    detail = "DATA.TBL is smaller than its header";
    return false;
  }
  const std::uint32_t count = read_be32(bytes.data());
  const std::uint32_t packs = read_be32(bytes.data() + 4);
  if (count != policy.data_table_entries || packs != policy.pack_count ||
      count == 0 || count > limits.maximum_table_entries ||
      bytes.size() != 8u + static_cast<std::uint64_t>(count) * 16u) {
    detail = "DATA.TBL shape or qualified counts mismatch";
    return false;
  }
  entries.clear();
  entries.reserve(count);
  for (std::uint32_t index = 0; index < count; ++index) {
    const std::uint8_t* row = bytes.data() + 8u + index * 16u;
    TableEntry entry;
    entry.index = index;
    entry.group = read_be32(row);
    entry.offset = read_be32(row + 4);
    entry.stored_size = read_be32(row + 8);
    entry.expanded_size = read_be32(row + 12);
    entry.archive = (entry.group & 0x01000000u) != 0
                        ? RetailArchive::Data01
                        : RetailArchive::Data00;
    entry.codec = (entry.group & 0x00020000u) != 0
                      ? RetailStorageCodec::Mode1PiXorRaw
                      : RetailStorageCodec::Mode1PiXorRawDeflate;
    const std::uint64_t archive_size =
        entry.archive == RetailArchive::Data00
            ? policy.identity.data00_size
            : policy.identity.data01_size;
    if (entry.stored_size == 0 || entry.expanded_size == 0 ||
        !add_within(entry.offset, entry.stored_size, archive_size)) {
      detail = "DATA.TBL contains an invalid PAC range at entry " +
               std::to_string(index);
      return false;
    }
    if (std::any_of(entries.begin(), entries.end(),
                    [&entry](const TableEntry& previous) {
                      return previous.archive == entry.archive &&
                             previous.offset == entry.offset &&
                             previous.stored_size == entry.stored_size;
                    })) {
      detail = "DATA.TBL contains a duplicate PAC range at entry " +
               std::to_string(index);
      return false;
    }
    entries.push_back(entry);
  }
  return true;
}

bool select_entries(const std::vector<TableEntry>& table,
                    std::span<const std::uint32_t> requested,
                    const RetailImportLimits& limits,
                    std::vector<TableEntry>& selected,
                    std::string& detail) {
  if (requested.empty()) {
    detail = "no DATA.TBL entries requested";
    return false;
  }
  selected.clear();
  std::uint64_t total = 0;
  for (const std::uint32_t index : requested) {
    if (index >= table.size()) {
      detail = "DATA.TBL entry out of range: " + std::to_string(index);
      return false;
    }
    if (std::any_of(selected.begin(), selected.end(),
                    [index](const TableEntry& entry) { return entry.index == index; })) {
      detail = "duplicate DATA.TBL entry: " + std::to_string(index);
      return false;
    }
    const TableEntry& entry = table[index];
    if (entry.stored_size > limits.maximum_stored_size ||
        entry.expanded_size > limits.maximum_expanded_size ||
        !add_within(total, entry.expanded_size,
                    limits.maximum_total_expanded_size)) {
      detail = "DATA.TBL entry exceeds import limits: " + std::to_string(index);
      return false;
    }
    total += entry.expanded_size;
    selected.push_back(entry);
  }
  std::sort(selected.begin(), selected.end(),
            [](const TableEntry& left, const TableEntry& right) {
              return left.index < right.index;
            });
  return true;
}

bool inflate_raw(std::span<const std::uint8_t> input, std::size_t output_size,
                 std::vector<std::uint8_t>& output) {
  if (input.size() > std::numeric_limits<uInt>::max() ||
      output_size > std::numeric_limits<uInt>::max()) {
    return false;
  }
  output.assign(output_size, 0);
  z_stream stream{};
  stream.next_in = const_cast<Bytef*>(input.data());
  stream.avail_in = static_cast<uInt>(input.size());
  stream.next_out = output.data();
  stream.avail_out = static_cast<uInt>(output.size());
  if (inflateInit2(&stream, -MAX_WBITS) != Z_OK) return false;
  const int result = inflate(&stream, Z_FINISH);
  const bool passed = result == Z_STREAM_END && stream.avail_in == 0 &&
                      stream.total_out == output_size;
  inflateEnd(&stream);
  if (!passed) output.clear();
  return passed;
}

bool decode_payload(std::vector<std::uint8_t> stored, const TableEntry& entry,
                    std::vector<std::uint8_t>& payload) {
  retail_mode1_xor(stored, entry.index);
  if (entry.codec == RetailStorageCodec::Mode1PiXorRaw) {
    if (stored.size() != entry.expanded_size) return false;
    payload = std::move(stored);
    return true;
  }
  return inflate_raw(stored, static_cast<std::size_t>(entry.expanded_size), payload);
}

bool write_file_sync(const std::filesystem::path& path,
                     std::span<const std::uint8_t> bytes) {
  const int descriptor = ::open(path.c_str(), O_WRONLY | O_CREAT | O_EXCL, 0600);
  if (descriptor < 0) return false;
  std::size_t written = 0;
  while (written < bytes.size()) {
    const ssize_t count = ::write(descriptor, bytes.data() + written,
                                  bytes.size() - written);
    if (count < 0 && errno == EINTR) continue;
    if (count <= 0) {
      ::close(descriptor);
      return false;
    }
    written += static_cast<std::size_t>(count);
  }
  const bool synced = ::fsync(descriptor) == 0;
  const bool closed = ::close(descriptor) == 0;
  return synced && closed;
}

void sync_directory(const std::filesystem::path& path) noexcept {
  const int descriptor = ::open(path.c_str(), O_RDONLY | O_DIRECTORY);
  if (descriptor >= 0) {
    (void)::fsync(descriptor);
    (void)::close(descriptor);
  }
}

bool rename_replace(const std::filesystem::path& from,
                    const std::filesystem::path& to) {
  if (::rename(from.c_str(), to.c_str()) != 0) return false;
  sync_directory(to.parent_path());
  return true;
}

bool verified_file(const std::filesystem::path& path, std::uint64_t size,
                   const Sha256Digest& digest) {
  std::error_code error;
  if (!std::filesystem::is_regular_file(path, error) || error ||
      std::filesystem::file_size(path, error) != size || error) {
    return false;
  }
  Sha256Digest actual{};
  return sha256_file(path, actual, size) && actual == digest;
}

class StagingDirectory final {
 public:
  bool create(const std::filesystem::path& cache) {
    std::error_code error;
    const std::filesystem::path parent = cache / ".staging";
    std::filesystem::create_directories(parent, error);
    if (error) return false;
    for (unsigned ordinal = 0; ordinal < 100; ++ordinal) {
      path_ = parent / ("import-" + std::to_string(::getpid()) + "-" +
                        std::to_string(ordinal));
      if (std::filesystem::create_directory(path_, error)) return true;
      if (error && error != std::errc::file_exists) return false;
      error.clear();
    }
    return false;
  }

  const std::filesystem::path& path() const noexcept { return path_; }

  ~StagingDirectory() {
    if (!path_.empty()) {
      std::error_code ignored;
      std::filesystem::remove_all(path_, ignored);
    }
  }

 private:
  std::filesystem::path path_;
};

bool publish_blob(const std::filesystem::path& cache,
                  const std::filesystem::path& staging,
                  std::span<const std::uint8_t> bytes,
                  const Sha256Digest& digest) {
  const std::filesystem::path destination = blob_path(cache, digest);
  if (verified_file(destination, bytes.size(), digest)) return true;
  std::error_code error;
  std::filesystem::create_directories(destination.parent_path(), error);
  if (error) return false;
  const std::filesystem::path temporary = staging / sha256_hex(digest);
  if (!write_file_sync(temporary, bytes)) return false;
  if (rename_replace(temporary, destination)) return true;
  std::filesystem::remove(temporary, error);
  return verified_file(destination, bytes.size(), digest);
}

std::vector<std::uint8_t> make_index(const RetailIdentityPolicy& policy,
                                     const std::vector<RetailContentRecord>& records,
                                     const Sha256Digest& media_manifest_sha256) {
  std::vector<std::uint8_t> bytes;
  bytes.reserve(kIndexHeaderSize + records.size() * kIndexRecordSize);
  bytes.insert(bytes.end(), kIndexMagic.begin(), kIndexMagic.end());
  append_u32(bytes, kIndexVersion);
  append_u32(bytes, kIndexHeaderSize);
  append_u32(bytes, kIndexRecordSize);
  append_u32(bytes, static_cast<std::uint32_t>(records.size()));
  append_u32(bytes, policy.data_table_entries);
  append_u32(bytes, policy.pack_count);
  append_digest(bytes, policy.identity.xex_sha256);
  append_digest(bytes, policy.identity.data_table_sha256);
  append_digest(bytes, policy.identity.data00_sha256);
  append_digest(bytes, policy.identity.data01_sha256);
  append_u64(bytes, policy.identity.xex_size);
  append_u64(bytes, policy.identity.data_table_size);
  append_u64(bytes, policy.identity.data00_size);
  append_u64(bytes, policy.identity.data01_size);
  append_digest(bytes, media_manifest_sha256);
  for (const RetailContentRecord& record : records) {
    append_u32(bytes, record.data_table_index);
    append_u32(bytes, record.group);
    bytes.push_back(static_cast<std::uint8_t>(record.archive));
    bytes.push_back(static_cast<std::uint8_t>(record.codec));
    bytes.push_back(0);
    bytes.push_back(0);
    append_u64(bytes, record.source_offset);
    append_u64(bytes, record.stored_size);
    append_u64(bytes, record.expanded_size);
    append_u64(bytes, record.payload_size);
    append_digest(bytes, record.stored_sha256);
    append_digest(bytes, record.payload_sha256);
  }
  return bytes;
}

bool publish_index(const std::filesystem::path& cache,
                   const std::filesystem::path& staging,
                   std::span<const std::uint8_t> index,
                   const Sha256Digest& digest) {
  std::error_code error;
  const std::filesystem::path directory = cache / "indices";
  std::filesystem::create_directories(directory, error);
  if (error) return false;
  const std::filesystem::path destination = directory / (sha256_hex(digest) + ".ac6idx");
  if (!verified_file(destination, index.size(), digest)) {
    const std::filesystem::path temporary = staging / "index.ac6idx";
    if (!write_file_sync(temporary, index)) return false;
    if (!rename_replace(temporary, destination) &&
        !verified_file(destination, index.size(), digest)) {
      return false;
    }
  }
  std::vector<std::uint8_t> current;
  current.insert(current.end(), kCurrentMagic.begin(), kCurrentMagic.end());
  append_u32(current, kIndexVersion);
  append_u32(current, kCurrentSize);
  append_digest(current, digest);
  const std::filesystem::path temporary = staging / "current";
  return write_file_sync(temporary, current) &&
         rename_replace(temporary, cache / "current");
}

class BinaryReader final {
 public:
  explicit BinaryReader(std::span<const std::uint8_t> bytes) : bytes_(bytes) {}

  bool magic(const std::array<std::uint8_t, 8>& expected) {
    if (remaining() < expected.size() ||
        !std::equal(expected.begin(), expected.end(), bytes_.begin() + offset_)) {
      return false;
    }
    offset_ += expected.size();
    return true;
  }

  bool u8(std::uint8_t& value) {
    if (remaining() < 1) return false;
    value = bytes_[offset_++];
    return true;
  }

  bool u16(std::uint16_t& value) {
    std::uint8_t high{}, low{};
    if (!u8(high) || !u8(low)) return false;
    value = static_cast<std::uint16_t>((high << 8u) | low);
    return true;
  }

  bool u32(std::uint32_t& value) {
    if (remaining() < 4) return false;
    value = read_be32(bytes_.data() + offset_);
    offset_ += 4;
    return true;
  }

  bool u64(std::uint64_t& value) {
    std::uint32_t high{}, low{};
    if (!u32(high) || !u32(low)) return false;
    value = (static_cast<std::uint64_t>(high) << 32u) | low;
    return true;
  }

  bool digest(Sha256Digest& value) {
    if (remaining() < value.size()) return false;
    std::copy_n(bytes_.begin() + offset_, value.size(), value.begin());
    offset_ += value.size();
    return true;
  }

  std::size_t remaining() const noexcept { return bytes_.size() - offset_; }

 private:
  std::span<const std::uint8_t> bytes_;
  std::size_t offset_{};
};

bool read_current(const std::filesystem::path& cache, Sha256Digest& index_digest,
                  std::string& detail) {
  std::vector<std::uint8_t> bytes;
  if (!read_file(cache / "current", kCurrentSize, bytes) ||
      bytes.size() != kCurrentSize) {
    detail = "cache current record is missing or truncated";
    return false;
  }
  BinaryReader reader(bytes);
  std::uint32_t version{}, size{};
  if (!reader.magic(kCurrentMagic) || !reader.u32(version) || !reader.u32(size) ||
      !reader.digest(index_digest) || reader.remaining() != 0 ||
      version != kIndexVersion || size != kCurrentSize) {
    detail = "cache current record is incompatible";
    return false;
  }
  return true;
}

bool parse_index(std::span<const std::uint8_t> bytes,
                 const RetailIdentityPolicy& policy,
                 const RetailImportLimits& limits,
                 RetailSourceIdentity& identity,
                 Sha256Digest& media_manifest_sha256,
                 std::vector<RetailContentRecord>& records,
                 std::string& detail) {
  BinaryReader reader(bytes);
  std::uint32_t version{}, header_size{}, record_size{}, record_count{};
  std::uint32_t table_entries{}, pack_count{};
  if (!reader.magic(kIndexMagic) || !reader.u32(version) ||
      !reader.u32(header_size) || !reader.u32(record_size) ||
      !reader.u32(record_count) || !reader.u32(table_entries) ||
      !reader.u32(pack_count) || version != kIndexVersion ||
      header_size != kIndexHeaderSize || record_size != kIndexRecordSize ||
      record_count == 0 || record_count > limits.maximum_table_entries ||
      table_entries != policy.data_table_entries || pack_count != policy.pack_count) {
    detail = "content index header is incompatible";
    return false;
  }
  if (!reader.digest(identity.xex_sha256) ||
      !reader.digest(identity.data_table_sha256) ||
      !reader.digest(identity.data00_sha256) ||
      !reader.digest(identity.data01_sha256) ||
      !reader.u64(identity.xex_size) || !reader.u64(identity.data_table_size) ||
      !reader.u64(identity.data00_size) || !reader.u64(identity.data01_size) ||
      !reader.digest(media_manifest_sha256) ||
      identity != policy.identity ||
      reader.remaining() != static_cast<std::size_t>(record_count) * record_size) {
    detail = "content index retail identity or size mismatch";
    return false;
  }
  records.clear();
  records.reserve(record_count);
  std::uint64_t total = 0;
  for (std::uint32_t ordinal = 0; ordinal < record_count; ++ordinal) {
    RetailContentRecord record;
    std::uint8_t archive{}, codec{};
    std::uint16_t reserved{};
    if (!reader.u32(record.data_table_index) || !reader.u32(record.group) ||
        !reader.u8(archive) || !reader.u8(codec) || !reader.u16(reserved) ||
        !reader.u64(record.source_offset) || !reader.u64(record.stored_size) ||
        !reader.u64(record.expanded_size) || !reader.u64(record.payload_size) ||
        !reader.digest(record.stored_sha256) ||
        !reader.digest(record.payload_sha256) || reserved != 0 || archive > 1 ||
        codec < 1 || codec > 2 || record.data_table_index >= table_entries ||
        record.stored_size == 0 || record.expanded_size == 0 ||
        record.payload_size == 0 ||
        record.stored_size > limits.maximum_stored_size ||
        record.expanded_size > limits.maximum_expanded_size ||
        record.payload_size > limits.maximum_expanded_size ||
        record.expanded_size != record.payload_size ||
        !add_within(total, record.payload_size,
                    limits.maximum_total_expanded_size) ||
        (!records.empty() &&
         record.data_table_index <= records.back().data_table_index)) {
      detail = "content index record is invalid at ordinal " +
               std::to_string(ordinal);
      records.clear();
      return false;
    }
    record.archive = static_cast<RetailArchive>(archive);
    record.codec = static_cast<RetailStorageCodec>(codec);
    const RetailArchive group_archive =
        (record.group & 0x01000000u) != 0 ? RetailArchive::Data01
                                         : RetailArchive::Data00;
    const RetailStorageCodec group_codec =
        (record.group & 0x00020000u) != 0
            ? RetailStorageCodec::Mode1PiXorRaw
            : RetailStorageCodec::Mode1PiXorRawDeflate;
    const std::uint64_t archive_size =
        record.archive == RetailArchive::Data00 ? identity.data00_size
                                                : identity.data01_size;
    const bool duplicate_range = std::any_of(
        records.begin(), records.end(), [&record](const RetailContentRecord& previous) {
          return previous.archive == record.archive &&
                 previous.source_offset == record.source_offset &&
                 previous.stored_size == record.stored_size;
        });
    if (record.archive != group_archive || record.codec != group_codec ||
        !add_within(record.source_offset, record.stored_size, archive_size) ||
        (record.codec == RetailStorageCodec::Mode1PiXorRaw &&
         record.stored_size != record.expanded_size) ||
        duplicate_range) {
      detail = "content index record metadata is inconsistent at ordinal " +
               std::to_string(ordinal);
      records.clear();
      return false;
    }
    total += record.payload_size;
    records.push_back(record);
  }
  return reader.remaining() == 0;
}

