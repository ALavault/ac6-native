const char* retail_content_error_name(RetailContentError error) noexcept {
  switch (error) {
    case RetailContentError::None: return "none";
    case RetailContentError::InvalidArgument: return "invalid_argument";
    case RetailContentError::SourceMissing: return "source_missing";
    case RetailContentError::SourceIdentityMismatch: return "source_identity_mismatch";
    case RetailContentError::DataTableInvalid: return "data_table_invalid";
    case RetailContentError::EntryDuplicate: return "entry_duplicate";
    case RetailContentError::EntryOutOfRange: return "entry_out_of_range";
    case RetailContentError::SourceRangeInvalid: return "source_range_invalid";
    case RetailContentError::SizeLimitExceeded: return "size_limit_exceeded";
    case RetailContentError::DecodeFailed: return "decode_failed";
    case RetailContentError::CacheIoFailed: return "cache_io_failed";
    case RetailContentError::CacheIncompatible: return "cache_incompatible";
    case RetailContentError::CacheIncomplete: return "cache_incomplete";
    case RetailContentError::CacheDigestMismatch: return "cache_digest_mismatch";
  }
  return "unknown";
}

void retail_mode1_xor(std::span<std::uint8_t> bytes,
                      std::uint32_t data_table_index) noexcept {
  const std::uint64_t pad = kMode1Pads[data_table_index & 0xffu];
  for (std::size_t index = 0; index < bytes.size(); ++index) {
    const unsigned shift = 56u - static_cast<unsigned>(index & 7u) * 8u;
    bytes[index] ^= static_cast<std::uint8_t>(pad >> shift);
  }
}

RetailContentImporter::RetailContentImporter(RetailIdentityPolicy policy,
                                             RetailImportLimits limits)
    : policy_(std::move(policy)), limits_(limits) {}

RetailImportReport RetailContentImporter::run(
    const std::filesystem::path& source_root,
    const std::filesystem::path& cache_root,
    std::span<const std::uint32_t> data_table_entries) const {
  RetailImportReport report;
  const auto fail = [&](RetailContentError error, std::string detail) {
    report.error = error;
    report.detail = std::move(detail);
    return report;
  };
  if (source_root.empty() || cache_root.empty() ||
      limits_.maximum_table_entries == 0) {
    return fail(RetailContentError::InvalidArgument,
                "source and cache roots must be non-empty");
  }

  const RetailContentError source_error =
      qualify_source_files(source_root, policy_, report.detail);
  if (source_error != RetailContentError::None) {
    report.error = source_error;
    return report;
  }

  std::vector<std::uint8_t> table_bytes;
  if (!read_file(source_root / "DATA.TBL", limits_.maximum_table_size,
                 table_bytes)) {
    return fail(RetailContentError::DataTableInvalid,
                "cannot read bounded DATA.TBL");
  }
  std::vector<TableEntry> table;
  if (!parse_table(table_bytes, policy_, limits_, table, report.detail)) {
    report.error = report.detail.find("duplicate PAC range") != std::string::npos
                       ? RetailContentError::EntryDuplicate
                       : RetailContentError::DataTableInvalid;
    return report;
  }
  std::vector<std::uint32_t> complete_entries;
  if (data_table_entries.empty()) {
    complete_entries.resize(table.size());
    std::iota(complete_entries.begin(), complete_entries.end(), 0u);
    data_table_entries = complete_entries;
  }
  std::vector<TableEntry> selected;
  if (!select_entries(table, data_table_entries, limits_, selected,
                      report.detail)) {
    if (report.detail.starts_with("duplicate")) {
      report.error = RetailContentError::EntryDuplicate;
    } else if (report.detail.find("out of range") != std::string::npos) {
      report.error = RetailContentError::EntryOutOfRange;
    } else if (report.detail.find("limits") != std::string::npos) {
      report.error = RetailContentError::SizeLimitExceeded;
    } else {
      report.error = RetailContentError::InvalidArgument;
    }
    return report;
  }

  std::error_code error;
  std::filesystem::create_directories(cache_root, error);
  if (error) return fail(RetailContentError::CacheIoFailed, "cannot create cache root");
  StagingDirectory staging;
  if (!staging.create(cache_root)) {
    return fail(RetailContentError::CacheIoFailed,
                "cannot create cache staging directory");
  }

  std::vector<RetailContentRecord> records;
  Sha256Digest media_manifest_sha256{};
  if (!import_retail_media(source_root, cache_root, staging.path(), policy_.media,
                           media_manifest_sha256, report.detail)) {
    report.error = RetailContentError::CacheIoFailed;
    return report;
  }
  records.reserve(selected.size());
  for (const TableEntry& entry : selected) {
    std::vector<std::uint8_t> stored;
    if (!read_range(archive_path(source_root, entry.archive), entry.offset,
                    entry.stored_size, stored)) {
      return fail(RetailContentError::SourceRangeInvalid,
                  "short PAC read at DATA.TBL entry " +
                      std::to_string(entry.index));
    }
    RetailContentRecord record;
    record.data_table_index = entry.index;
    record.group = entry.group;
    record.archive = entry.archive;
    record.codec = entry.codec;
    record.source_offset = entry.offset;
    record.stored_size = entry.stored_size;
    record.expanded_size = entry.expanded_size;
    record.stored_sha256 = sha256_bytes(stored);
    std::vector<std::uint8_t> payload;
    if (!decode_payload(std::move(stored), entry, payload)) {
      return fail(RetailContentError::DecodeFailed,
                  "mode-1 decode failed at DATA.TBL entry " +
                      std::to_string(entry.index));
    }
    record.payload_size = payload.size();
    record.payload_sha256 = sha256_bytes(payload);
    if (!publish_blob(cache_root, staging.path(), payload,
                      record.payload_sha256)) {
      return fail(RetailContentError::CacheIoFailed,
                  "cannot publish payload blob at DATA.TBL entry " +
                      std::to_string(entry.index));
    }
    report.imported_bytes += payload.size();
    records.push_back(record);
  }

  // Re-qualify after all bounded reads. This closes the source mutation window:
  // an index is never published under the PAL identity if a PAC changed while
  // the importer was decoding it.
  const RetailContentError final_source_error =
      qualify_source_files(source_root, policy_, report.detail);
  if (final_source_error != RetailContentError::None) {
    report.error = final_source_error;
    return report;
  }

  const std::vector<std::uint8_t> index = make_index(policy_, records,
                                                     media_manifest_sha256);
  report.index_sha256 = sha256_bytes(index);
  if (!publish_index(cache_root, staging.path(), index, report.index_sha256)) {
    return fail(RetailContentError::CacheIoFailed,
                "cannot atomically publish content index");
  }
  report.imported_records = records.size();
  report.error = RetailContentError::None;
  return report;
}

RetailContentStore::RetailContentStore(RetailIdentityPolicy policy,
                                       RetailImportLimits limits)
    : policy_(std::move(policy)), limits_(limits) {}

bool RetailContentStore::fail(RetailContentError error, std::string detail) {
  records_.clear();
  error_ = error;
  detail_ = std::move(detail);
  return false;
}

void RetailContentStore::close() noexcept {
  cache_root_.clear();
  identity_ = {};
  index_sha256_ = {};
  records_.clear();
  media_ = RetailMediaStore{};
  error_ = RetailContentError::CacheIncomplete;
  detail_.clear();
}

bool RetailContentStore::open(const std::filesystem::path& cache_root) {
  close();
  if (cache_root.empty()) {
    return fail(RetailContentError::InvalidArgument, "cache root is empty");
  }
  Sha256Digest index_digest{};
  if (!read_current(cache_root, index_digest, detail_)) {
    return fail(detail_.find("incompatible") != std::string::npos
                    ? RetailContentError::CacheIncompatible
                    : RetailContentError::CacheIncomplete,
                detail_);
  }
  const std::filesystem::path index_path =
      cache_root / "indices" / (sha256_hex(index_digest) + ".ac6idx");
  const std::uint64_t maximum_index_size =
      kIndexHeaderSize +
      static_cast<std::uint64_t>(limits_.maximum_table_entries) * kIndexRecordSize;
  std::vector<std::uint8_t> index;
  if (!read_file(index_path, maximum_index_size, index)) {
    return fail(RetailContentError::CacheIncomplete,
                "content index is missing or too large");
  }
  if (sha256_bytes(index) != index_digest) {
    return fail(RetailContentError::CacheDigestMismatch,
                "content index digest mismatch");
  }
  Sha256Digest media_manifest_sha256{};
  if (!parse_index(index, policy_, limits_, identity_, media_manifest_sha256,
                   records_, detail_)) {
    return fail(RetailContentError::CacheIncompatible, detail_);
  }
  if (policy_.media.required) {
    if (!media_.open(cache_root, policy_.media) ||
        media_.manifest_sha256() != media_manifest_sha256) {
      return fail(RetailContentError::CacheIncomplete,
                  "content index references an unavailable media manifest");
    }
  } else if (media_manifest_sha256 != Sha256Digest{}) {
    return fail(RetailContentError::CacheIncompatible,
                "optional media policy cannot open a media-bound index");
  }
  for (const RetailContentRecord& record : records_) {
    if (!verified_file(blob_path(cache_root, record.payload_sha256),
                       record.payload_size, record.payload_sha256)) {
      return fail(RetailContentError::CacheIncomplete,
                  "payload blob is missing or corrupt for DATA.TBL entry " +
                      std::to_string(record.data_table_index));
    }
  }
  cache_root_ = cache_root;
  index_sha256_ = index_digest;
  error_ = RetailContentError::None;
  detail_.clear();
  return true;
}

const RetailContentRecord* RetailContentStore::find(
    std::uint32_t data_table_index) const noexcept {
  const auto found = std::lower_bound(
      records_.begin(), records_.end(), data_table_index,
      [](const RetailContentRecord& record, std::uint32_t index) {
        return record.data_table_index < index;
      });
  return found != records_.end() && found->data_table_index == data_table_index
             ? &*found
             : nullptr;
}

bool RetailContentStore::read_payload(std::uint32_t data_table_index,
                                      std::vector<std::uint8_t>& payload) const {
  const RetailContentRecord* record = find(data_table_index);
  if (record == nullptr ||
      !read_file(blob_path(cache_root_, record->payload_sha256),
                 limits_.maximum_expanded_size, payload) ||
      payload.size() != record->payload_size ||
      sha256_bytes(payload) != record->payload_sha256) {
    payload.clear();
    return false;
  }
  return true;
}

std::filesystem::path default_retail_cache_root() {
  if (const char* xdg = std::getenv("XDG_CACHE_HOME"); xdg != nullptr && *xdg != 0) {
    const std::filesystem::path root(xdg);
    if (root.is_absolute()) return root / "ac6-native";
  }
  if (const char* home = std::getenv("HOME"); home != nullptr && *home != 0) {
    const std::filesystem::path root(home);
    if (root.is_absolute()) return root / ".cache" / "ac6-native";
  }
  return {};
}

